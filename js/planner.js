const Planner = {
  apiBase: (location.protocol === "file:" ? "http://127.0.0.1:8000" : ""),
  aiMode: true,
  money(n){ return new Intl.NumberFormat("en-IN",{style:"currency",currency:"INR",maximumFractionDigits:0}).format(n); },
  save(plan){
    const user=Auth.current(); if(!user) return;
    const key=`pocketsmart_plans_${user.id}`;
    const plans=JSON.parse(localStorage.getItem(key)||"[]");
    plans.unshift({...plan,id:crypto.randomUUID?.()||String(Date.now()),createdAt:new Date().toISOString()});
    localStorage.setItem(key,JSON.stringify(plans));
  },
  plans(){ const u=Auth.current(); return u?JSON.parse(localStorage.getItem(`pocketsmart_plans_${u.id}`)||"[]"):[]; },
  async callApi(endpoint,payload){
    if(!this.apiBase) return null;
    const response=await fetch(`${this.apiBase}${endpoint}`,{method:"POST",body:payload instanceof FormData?payload:JSON.stringify(payload),headers:payload instanceof FormData?{}:{"Content-Type":"application/json"}});
    if(!response.ok) throw new Error("Backend request failed.");
    return response.json();
  },
  home(data){
    const budget=Number(data.budget);
    const selected=data.rooms.length?data.rooms:["Living Room"];
    const base=[["Lighting",Math.round(budget*.18)],["Fans & fixtures",Math.round(budget*.10)],["Furniture",Math.round(budget*.42)],["Dining",Math.round(budget*.15)]];
    const used=base.reduce((a,b)=>a+b[1],0);
    base.push(["Flexible / special",Math.max(0,budget-used)]);
    return {type:"home",title:"Home interior plan",budget,summary:`${selected.join(", ")} • ${data.lights} lights • ${data.fans} fans`,allocations:base.map(([label,amount])=>({label,amount})),details:data};
  },
  party(data){
    const budget=Number(data.budget), active=[];
    if(data.catering) active.push(["Catering",.50]);
    if(data.decor) active.push(["Decoration",.25]);
    if(data.entertainment) active.push(["Entertainment",.15]);
    if(!active.length) active.push(["General event",1]);
    const total=active.reduce((a,b)=>a+b[1],0);
    let allocations=active.map(([label,p])=>({label,amount:Math.round(budget*p/total)}));
    const used=allocations.reduce((a,b)=>a+b.amount,0);
    allocations.push({label:"Buffer",amount:Math.max(0,budget-used)});
    return {type:"party",title:"Party budget plan",budget,summary:`${data.guests} guests • ${data.type} • ${data.venue}`,allocations,details:data};
  },
  jewelry(data){
    const budget=Number(data.budget);
    const allocations=[["Necklace / set",Math.round(budget*.42)],["Earrings",Math.round(budget*.22)],["Bracelet / bangles",Math.round(budget*.18)],["Reserve for matching",Math.round(budget*.18)]];
    return {type:"jewelry",title:"Jewelry match plan",budget,summary:`${data.occasion} • ${data.style}`,allocations:allocations.map(([label,amount])=>({label,amount})),details:data,
      recommendations:[
        {symbol:"◇",name:`${data.style} necklace`,desc:"A balanced centerpiece within your budget.",platform:"Amazon / Flipkart"},
        {symbol:"◈",name:"Matching earrings",desc:"Choose a pair that echoes the main piece.",platform:"Jewelry marketplace"},
        {symbol:"✦",name:"Finishing piece",desc:"A bracelet or bangles can complete the look.",platform:"Tanishq / CaratLane"}
      ]};
  }
};

function renderPlanResult(plan){
  const total=plan.allocations.reduce((a,b)=>a+b.amount,0);
  let html=`<div class="result-header"><span class="eyebrow">${plan.type.toUpperCase()} PLAN</span><h2>${plan.title}</h2><p class="muted">${plan.summary}</p><strong>${Planner.money(plan.budget)} total budget</strong></div>`;
  if(plan.recommendations){
    html+=`<div class="recommendation-grid">${plan.recommendations.map((r,i)=>`<div class="rec-card"><div class="rec-symbol">${r.symbol||["◇","◈","✦","○"][i%4]}</div><h3>${r.name}</h3><p>${r.description||r.desc||"Personalized recommendation."}</p><small>${r.budget_amount?Planner.money(r.budget_amount):r.platform||"PocketSmart AI"}</small></div>`).join("")}</div><br>`;
  }
  html+=`<h3>Suggested allocation</h3>`;
  html+=plan.allocations.map(a=>`<div class="allocation-card"><div><strong>${a.label}</strong>${a.reason?`<small class="muted">${a.reason}</small>`:""}<div class="allocation-bar"><i style="width:${Math.min(100,(a.amount/plan.budget)*100)}%"></i></div></div><div class="amount">${Planner.money(a.amount)}</div></div>`).join("");
  if(plan.tips?.length){ html+=`<div class="panel" style="margin-top:18px"><h3>AI tips</h3><ul class="muted">${plan.tips.map(t=>`<li>${t}</li>`).join("")}</ul></div>`; }
  html+=`<p class="muted" style="margin-top:16px;font-size:12px">${plan.title?.startsWith("AI")?"Generated by Gemini through the FastAPI backend.":"Demo allocation generated in the browser."}</p>`;
  document.getElementById("resultContent").innerHTML=html;
  document.getElementById("resultModal").classList.remove("hidden");
}
